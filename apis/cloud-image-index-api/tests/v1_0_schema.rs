//! The 1.0 promise, checked on the schema: within `v1/`, the format only
//! gains optional fields and open-enum values. Compared with the OpenAPI
//! document 1.0 published (`tests/typify-client/fixtures/v1.0/`), every
//! published path must answer with the same schema, every schema and
//! property must still be there with the same shape, no
//! field may become required or stop being required, `OsFamily` keeps
//! its values, and each open enum keeps the values it had. Descriptions
//! may change.
//!
//! Parsing documents (`tests/typify-client/tests/v1_0_compat.rs`) cannot
//! see a renamed optional field, which an old client just reads as
//! absent; this can.

use std::collections::BTreeSet;
use std::path::Path;

use serde_json::{Map, Value};
use sha2::{Digest, Sha256};

const FIXTURES: &str = "../../tests/typify-client/fixtures/v1.0";

/// The fixture files' SHA-256, so they cannot be regenerated by
/// accident: that would make every 1.0 check compare the code with
/// itself.
const FIXTURE_SHA256: &[(&str, &str)] = &[
    (
        "openapi.json",
        "75efdfff8896d577819e19d6433c4c3c73840b017565539a5a18dde55448b01d",
    ),
    (
        "images.json",
        "98265b19e5fd8ea97e14a4dd9fbf4a1964d2d8ca19afd5c6af3607d91aa58ca5",
    ),
    (
        "index.json",
        "3499c8bc9d2612a60d537365d465e466db7ebaf5e1fd5f6177897e62ba45fa63",
    ),
];

fn fixture(name: &str) -> Result<Vec<u8>, String> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join(FIXTURES)
        .join(name);
    std::fs::read(&path).map_err(|e| format!("read {path:?}: {e}"))
}

#[test]
fn the_1_0_fixtures_are_unchanged() -> Result<(), String> {
    for (name, expected) in FIXTURE_SHA256 {
        let got = Sha256::digest(fixture(name)?)
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect::<String>();
        assert_eq!(
            &got, expected,
            "{name} changed; the 1.0 fixtures are never regenerated"
        );
    }
    Ok(())
}

/// A schema with every `description` removed, for comparing shapes.
fn shape(v: &Value) -> Value {
    match v {
        Value::Object(map) => Value::Object(
            map.iter()
                .filter(|(k, _)| k.as_str() != "description")
                .map(|(k, v)| (k.clone(), shape(v)))
                .collect(),
        ),
        Value::Array(items) => Value::Array(items.iter().map(shape).collect()),
        other => other.clone(),
    }
}

/// The values an open enum's description lists (`- `value``).
fn known_values(schema: &Value) -> Option<BTreeSet<String>> {
    let description = schema.get("description")?.as_str()?;
    let (_, list) = description.split_once("Known values:")?;
    Some(
        list.lines()
            .filter_map(|l| l.trim().strip_prefix("- `"))
            .filter_map(|l| l.split_once('`').map(|(v, _)| v.to_string()))
            .collect(),
    )
}

fn required(schema: &Value) -> BTreeSet<String> {
    schema["required"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|v| v.as_str().map(str::to_string))
        .collect()
}

/// Every way `now` breaks a client of `then`, as messages.
fn breaks(then: &Value, now: &Value) -> Vec<String> {
    let empty = Map::new();
    let schemas = |doc: &Value| {
        doc.pointer(SCHEMAS)
            .and_then(Value::as_object)
            .cloned()
            .unwrap_or_else(|| empty.clone())
    };
    let (old, new) = (schemas(then), schemas(now));
    let mut problems = Vec::new();
    for (name, was) in &old {
        let Some(is) = new.get(name) else {
            problems.push(format!("{name}: schema removed"));
            continue;
        };
        if was.get("properties").is_none() {
            // An enum, open or closed.
            if shape(was) != shape(is) {
                problems.push(format!("{name}: shape changed"));
            }
            if let Some(had) = known_values(was) {
                let has = known_values(is).unwrap_or_default();
                for value in had.difference(&has) {
                    problems.push(format!("{name}: value {value:?} removed"));
                }
            }
            continue;
        }
        // The schema's own keys (type, nullable, allOf ...), apart from
        // its fields, which are compared one by one below.
        let own = |s: &Value| {
            let mut s = shape(s);
            if let Some(map) = s.as_object_mut() {
                map.remove("properties");
                map.remove("required");
            }
            s
        };
        if own(was) != own(is) {
            problems.push(format!("{name}: shape changed"));
        }
        if required(was) != required(is) {
            problems.push(format!(
                "{name}: required was {:?}, is {:?}",
                required(was),
                required(is)
            ));
        }
        let props = |s: &Value| s["properties"].as_object().cloned().unwrap_or_default();
        let (had, has) = (props(was), props(is));
        for (field, schema) in &had {
            match has.get(field) {
                None => problems.push(format!("{name}.{field}: removed")),
                Some(now) if shape(schema) != shape(now) => {
                    problems.push(format!("{name}.{field}: shape changed"))
                }
                Some(_) => {}
            }
        }
        let rest: Vec<_> = has.keys().filter(|f| !had.contains_key(*f)).collect();
        for field in rest {
            if required(is).contains(field) {
                problems.push(format!("{name}.{field}: added as required"));
            }
        }
    }
    // Each published path, and what it answers with.
    let paths = |doc: &Value| doc["paths"].as_object().cloned().unwrap_or_default();
    let new_paths = paths(now);
    for (path, was) in &paths(then) {
        let response = |p: &Value| shape(&p["get"]["responses"]["200"]);
        match new_paths.get(path) {
            None => problems.push(format!("{path}: removed")),
            Some(is) if response(was) != response(is) => {
                problems.push(format!("{path}: response changed"))
            }
            Some(_) => {}
        }
    }
    problems
}

fn the_1_0_document() -> Result<Value, String> {
    serde_json::from_slice(&fixture("openapi.json")?).map_err(|e| e.to_string())
}

#[test]
fn the_format_has_changed_only_compatibly_since_1_0() -> Result<(), String> {
    let problems = breaks(&the_1_0_document()?, &cloud_image_index_api::openapi()?);
    assert!(problems.is_empty(), "{problems:#?}");
    Ok(())
}

/// Where an OpenAPI document keeps its schemas.
const SCHEMAS: &str = "/components/schemas";

/// An edit to an OpenAPI document.
type Edit = Box<dyn Fn(&mut Value)>;

/// The check itself: each kind of breaking change is reported.
#[test]
fn breaking_changes_are_reported() -> Result<(), String> {
    let then = the_1_0_document()?;
    let edited = |edit: &dyn Fn(&mut Value)| {
        let mut now = then.clone();
        edit(&mut now);
        breaks(&then, &now)
    };
    let cases: Vec<(&str, Edit)> = vec![
        (
            "DistroSummary.homepage: removed",
            Box::new(|v| {
                let p = v.pointer_mut(&format!("{SCHEMAS}/DistroSummary/properties"));
                if let Some(Value::Object(p)) = p {
                    let homepage = p.remove("homepage");
                    p.insert("home_page".into(), homepage.unwrap_or_default());
                }
            }),
        ),
        (
            "Build.build: shape changed",
            Box::new(|v| {
                if let Some(t) = v.pointer_mut(&format!("{SCHEMAS}/Build/properties/build")) {
                    t["nullable"] = true.into();
                }
            }),
        ),
        (
            "Build: required was",
            Box::new(|v| {
                if let Some(r) = v.pointer_mut(&format!("{SCHEMAS}/Build/required")) {
                    *r = serde_json::json!(["artifacts"]);
                }
            }),
        ),
        (
            "Artifact.size2: added as required",
            Box::new(|v| {
                if let Some(a) = v.pointer_mut(&format!("{SCHEMAS}/Artifact")) {
                    a["properties"]["size2"] = serde_json::json!({"type": "integer"});
                    if let Some(r) = a["required"].as_array_mut() {
                        r.push("size2".into());
                    }
                }
            }),
        ),
        (
            "DigestAlgorithm: value \"sha256\" removed",
            Box::new(|v| {
                if let Some(d) = v.pointer_mut(&format!("{SCHEMAS}/DigestAlgorithm/description")) {
                    *d = d
                        .as_str()
                        .unwrap_or_default()
                        .replace("- `sha256`", "- `sha-256`")
                        .into();
                }
            }),
        ),
        (
            "OsFamily: shape changed",
            Box::new(|v| {
                if let Some(Value::Array(e)) = v.pointer_mut(&format!("{SCHEMAS}/OsFamily/enum")) {
                    e.push("windows".into());
                }
            }),
        ),
        (
            "Compression: shape changed",
            Box::new(|v| {
                if let Some(c) = v.pointer_mut(&format!("{SCHEMAS}/Compression")) {
                    c["enum"] = serde_json::json!(["none", "gzip", "xz", "zstd", "bzip2"]);
                }
            }),
        ),
        (
            "OsinfoRef: schema removed",
            Box::new(|v| {
                if let Some(Value::Object(s)) = v.pointer_mut(SCHEMAS) {
                    s.remove("OsinfoRef");
                }
            }),
        ),
        (
            "/v1/images.json: response changed",
            Box::new(|v| {
                let at =
                    "/paths/~1v1~1images.json/get/responses/200/content/application~1json/schema";
                if let Some(schema) = v.pointer_mut(at) {
                    *schema = serde_json::json!({"$ref": "#/components/schemas/DistroList"});
                }
            }),
        ),
        (
            "/v1/index.json: removed",
            Box::new(|v| {
                if let Some(Value::Object(paths)) = v.pointer_mut("/paths") {
                    paths.remove("/v1/index.json");
                }
            }),
        ),
        (
            "DistroSummary: shape changed",
            Box::new(|v| {
                if let Some(s) = v.pointer_mut(&format!("{SCHEMAS}/DistroSummary")) {
                    s["nullable"] = true.into();
                }
            }),
        ),
    ];
    for (expected, edit) in &cases {
        let problems = edited(edit.as_ref());
        assert!(
            problems.iter().any(|p| p.starts_with(expected)),
            "{expected}: {problems:#?}"
        );
    }
    // Compatible changes are not reported.
    let compatible = edited(&|v| {
        if let Some(s) = v.pointer_mut(&format!("{SCHEMAS}/DistroSummary")) {
            s["properties"]["mirror_count"] =
                serde_json::json!({"type": "integer", "nullable": true});
            s["description"] = "Reworded.".into();
        }
        if let Some(d) = v.pointer_mut(&format!("{SCHEMAS}/Compression/description")) {
            *d = format!("{}\n- `lz4`", d.as_str().unwrap_or_default()).into();
        }
    });
    assert!(compatible.is_empty(), "{compatible:#?}");
    Ok(())
}
